/** 展开成对象，并预先算好小写索引字段，避免每次搜索重复 toLowerCase */
export const CITIES = RAW.map(([name, pinyin, initial, lat, lon, admin1, country, population]) => ({
  name,
  pinyin,
  initial,
  lat,
  lon,
  admin1,
  country,
  countryCode: country === '中国' ? 'CN' : '',
  population,
  // 索引字段
  _n: name.toLowerCase(),
  _p: pinyin.toLowerCase(),
  _i: initial.toLowerCase(),
  _a: admin1.toLowerCase(),
  _c: country.toLowerCase(),
  source: 'local',
}))

/**
 * 本地匹配。命中规则按优先级：
 *   1) 名称前缀（"杭" → 杭州）
 *   2) 全拼前缀（"hangz" → 杭州）
 *   3) 首字母缩写前缀（"hz" → 杭州）
 *   4) 名称/行政区/国家包含（"州" → 广州、杭州、郑州…）
 * 同优先级内按人口降序，人口相同的按名称稳定排序。
 *
 * @param {string} kw 已 trim 的关键词
 * @param {number} limit 最多返回条数
 */
export function matchLocal(kw, limit = 12) {
  const k = String(kw || '').trim().toLowerCase()
  if (!k) return []

  const scored = []
  for (const c of CITIES) {
    let score = -1
    if (c._n === k) score = 100           // 完全等于
    else if (c._n.startsWith(k)) score = 90
    else if (c._p === k) score = 85
    else if (c._p.startsWith(k)) score = 80
    else if (c._i === k) score = 75
    else if (c._i.startsWith(k)) score = 70
    else if (c._n.includes(k)) score = 60
    else if (c._a.startsWith(k)) score = 50
    else if (c._c.startsWith(k)) score = 45
    else if (c._p.includes(k)) score = 40
    else if (c._a.includes(k)) score = 35

    if (score >= 0) scored.push({ c, score })
  }

  scored.sort((a, b) => {
    if (b.score !== a.score) return b.score - a.score
    if (b.c.population !== a.c.population) return b.c.population - a.c.population
    return a.c.name.localeCompare(b.c.name, 'zh')
  })

  return scored.slice(0, limit).map(x => x.c)
}

